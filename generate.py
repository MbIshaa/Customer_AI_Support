def random_date():
    days = (END_DATE - START_DATE).days
    return START_DATE + timedelta(days=random.randint(0, days))


def choose_category(date):
    month = date.month

    weights = {
        "Доставка": 20,
        "Оплата": 13,
        "Возвраты": 10,
        "Качество товара": 10,
        "Поддержка": 12,
        "Мобильное приложение": 8,
        "Личный кабинет": 7,
        "Бонусная программа": 7,
        "Цена": 8,
        "Документы": 5,
    }

    # Летом искусственно увеличиваем проблемы с доставкой
    if month in [6, 7, 8]:
        weights["Доставка"] += 18

    # В сентябре имитируем неудачное обновление приложения
    if month == 9:
        weights["Мобильное приложение"] += 30

    # В ноябре имитируем рост проблем с платежами
    if month == 11:
        weights["Оплата"] += 25

    # В декабре растет нагрузка на доставку и поддержку
    if month == 12:
        weights["Доставка"] += 25
        weights["Поддержка"] += 15

    categories = list(weights.keys())
    probabilities = list(weights.values())

    return random.choices(
        categories,
        weights=probabilities,
        k=1
    )[0]


rows = []

for request_id in range(1, 1001):
    date = random_date()
    category = choose_category(date)

    theme, text = random.choice(templates[category])

    addition = random.choice(additions)

    if addition:
        text = f"{text} {addition}"

    rows.append(
        {
            "id": request_id,
            "date": date.strftime("%Y-%m-%d"),
            "theme": theme,
            "text": text,
            "category": category,
        }
    )


df = pd.DataFrame(rows)
df = df.sort_values("date")

